/**
 * Generates supabase/seed.sql from the TypeScript demo dataset so the database
 * seed and the offline demo stay identical. Run: pnpm db:seed:generate
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { domainToRow } from "../src/mapping";
import * as d from "../src/demo/dataset";

export function sqlLiteral(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error("non-finite number");
    return String(v);
  }
  if (typeof v === "string") return `'${v.replace(/'/g, "''")}'`;
  return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
}

export function insertSql(table: string, rows: object[]): string {
  if (!rows.length) return "";
  const mapped = rows.map((r) => domainToRow(r as Record<string, unknown>));
  const cols = [...new Set(mapped.flatMap((r) => Object.keys(r)))];
  const values = mapped.map((r) => `  (${cols.map((c) => sqlLiteral(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (id) do nothing;\n`;
}

export function buildSeed(): string {
  const parts = [
    "-- GENERATED by packages/data/scripts/generate-seed.ts — do not edit by hand.",
    "-- FICTIONAL DEMONSTRATION DATA. Not official information about any real university.",
    "begin;",
    insertSql("universities", [d.demoUniversity]),
    insertSql("campuses", d.demoCampuses),
    insertSql("buildings", d.demoBuildings),
    insertSql("floors", d.demoFloors),
    insertSql("navigation_nodes", d.demoNavNodes),
    insertSql("navigation_edges", d.demoNavEdges),
    insertSql("departments", d.demoDepartments),
    insertSql("rooms", d.demoRooms),
    insertSql("map_elements", d.demoMapElements),
    insertSql("qr_checkpoints", d.demoCheckpoints),
    insertSql("lecturers", d.demoLecturers),
    insertSql("courses", d.demoCourses),
    insertSql("student_groups", d.demoGroups),
    insertSql("semesters", d.demoSemesters),
    insertSql("timetable_entries", d.demoTimetable),
    insertSql("schedule_changes", d.demoScheduleChanges),
    insertSql("announcements", d.demoAnnouncements),
    "commit;",
  ];
  return parts.filter(Boolean).join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(dirname(fileURLToPath(import.meta.url)), "../../../supabase/seed.sql");
  writeFileSync(out, buildSeed());
  console.log(`wrote ${out}`);
}
